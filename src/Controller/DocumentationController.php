<?php

namespace Aliarteo\AliDocsBundle\Controller;

use Symfony\Component\Finder\Finder;
use Aliarteo\AliDocsBundle\Entity\DocFile;
use Symfony\Component\Form\FormError;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;
use Aliarteo\AliDocsBundle\Form\MarkdownEditorType;
use Aliarteo\AliDocsBundle\Markdown\MarkdownParser;
use Symfony\Component\HttpFoundation\ResponseHeaderBag;
use Aliarteo\AliDocsBundle\Service\DocumentationService;
use Symfony\Component\HttpFoundation\BinaryFileResponse;
use Symfony\Contracts\Translation\TranslatorInterface;
use Symfony\Bundle\FrameworkBundle\Controller\AbstractController;

/**
 * The routes are generated by the AliDocsRoutingLoader (one set of routes per documentation)
 */
class DocumentationController extends AbstractController
{

    public function __construct(
        private DocumentationService $documentationService,
    ) {
    }

    /**
     * index
     * The route looks like : #[Route('/{doc_key}', name: 'ali_docs_index')]
     *
     * @param  mixed $doc_key
     * @return Response
     */
    public function index(string $doc_key): Response
    {
        // Security
        $security = $this->getViewDocSecurity($doc_key);
        if ($security) {
            $this->denyAccessUnlessGranted($security);
        }

        // Root Documentation Directory
        $doc_path = $this->getDocDir($doc_key);
        // Tree files/folder Documentation Directory
        $tree = $this->documentationService->getDirectoryTree($doc_path, null);

        $arg_render['doc_key'] = $doc_key;
        $arg_render['doc_title'] = $this->getDocTitle($doc_key);
        $arg_render['tree'] = $tree;
        // Home cards : consecutive folders / pages grouped together (one row per group)
        $arg_render['groups'] = $this->documentationService->groupChildrenByType($tree);
        // Page cards : short intro from the page content
        $arg_render['intros'] = $this->documentationService->getPagesIntro($tree->getChildren(), $doc_path);

        $template = "@AliDocs/documentation/index.html.twig";
        return $this->render($template, $arg_render);

    }

    /**
     * show
     * The route looks like : #[Route('/{doc_key}/{path}{extension}', name: 'ali_docs_show', requirements: ['path' => '.+'])]
     *
     * @param  mixed $doc_key
     * @param  mixed $path
     * @return Response
     */
    public function show(MarkdownParser $markdownParser, string $doc_key, string $path, string $extension = null): Response
    {
        // Security first : no information (404 page...) on a documentation the user can not read
        $security = $this->getViewDocSecurity($doc_key);
        if ($security) {
            $this->denyAccessUnlessGranted($security);
        }

        $this->denyUnsafePath($path);

        // Internal link to a markdown file (ex : [Menus](../15__Wordpress/10__Menus.md)) : redirect to the page
        if ('md' === strtolower(pathinfo($path, PATHINFO_EXTENSION))) {
            return $this->redirectToRoute('ali_docs_show', [
                'doc_key' => $doc_key,
                'path' => substr($path, 0, -3),
            ]);
        }

        // If Url is an asset
        $gessExtension = pathinfo($path, PATHINFO_EXTENSION) ?: null;
        if (!empty($extension) || !empty($gessExtension)) {
            return $this->asset($doc_key, $path, $extension);
        }

        $edit_security = $this->getEditDocSecurity($doc_key);

        // Root Documentation Directory
        $doc_path = $this->getDocDir($doc_key);
        $tree = $this->documentationService->getDirectoryTree($doc_path);

        // Folder : index of its sub-folders and pages (searched in the tree : no access outside the documentation)
        $folder = $this->documentationService->findDirectory($tree, $path);
        if ($folder && '' !== $folder->getUrl()) {
            return $this->render('@AliDocs/documentation/folder.html.twig', [
                'doc_key' => $doc_key,
                'doc_title' => $this->getDocTitle($doc_key),
                'folder' => $folder,
                'path' => $folder->getUrl(),
                'breadcrumb' => $this->documentationService->getBreadcrumbFolders($folder->getUrl()),
                'groups' => $this->documentationService->groupChildrenByType($folder),
                'intros' => $this->documentationService->getPagesIntro($folder->getChildren(), $doc_path),
            ]);
        }

        // Doc file Content
        $filePath = $doc_path . "/" . $path . '.md';
        if (!is_file($filePath)) {
            throw $this->createNotFoundException("The page \"$path\" does not exist.");
        }
        $docFileContent = $this->documentationService->getDocFileContent($filePath);

        // Content Markdown to html : the HTML of the page is cleaned (no script, iframe, events...)
        $htmlContent = $markdownParser->toHtml($docFileContent);
        // Relative images / videos : absolute urls (Turbo inserts the page before changing the browser url)
        $htmlContent = $markdownParser->replaceSrcUrls($htmlContent, $doc_key, $path);

        $fileName = pathinfo($filePath, PATHINFO_FILENAME);
        $fileRelativePath = DIRECTORY_SEPARATOR . $path;
        $depth = count(explode('/', $path));
        $docFile = new DocFile($fileName, $fileRelativePath, $depth);

        // Previous / Next pages
        $prevNext = $this->documentationService->getPrevNextFiles($tree, $path);

        $arg_render['doc_key'] = $doc_key;
        $arg_render['doc_file'] = $docFile;
        $arg_render['breadcrumb'] = $this->documentationService->getBreadcrumbFolders($path);
        $arg_render['prev_file'] = $prevNext['prev'];
        $arg_render['next_file'] = $prevNext['next'];
        $arg_render['doc_title'] = $this->getDocTitle($doc_key);
        $arg_render['content'] = $htmlContent;
        $arg_render['edit_security'] = $edit_security;
        $arg_render['path'] = $path;
        $template = "@AliDocs/documentation/show.html.twig";

        return $this->render($template, $arg_render);

    }

    /**
     * edit
     * The route looks like : 
     * #[Route('{admin_path}/{doc_key}/{path}', name: 'ali_docs_admin_edit', requirements: ['path' => '.+'])]
     *
     * @param  mixed $doc_key
     * @param  mixed $path
     * @return Response
     */
    public function edit(MarkdownParser $markdownParser, TranslatorInterface $translator, Request $request, string $doc_key, string $path): Response
    {
        // Security first : the edition always requires a role (it writes files on the server)
        $edit_security = $this->getEditDocSecurity($doc_key);
        if ('' === $edit_security) {
            throw $this->createAccessDeniedException('No edit_security configured for this documentation.');
        }
        $this->denyAccessUnlessGranted($edit_security);

        // The edit page shows the content : the user must also be allowed to read the documentation
        $view_security = $this->getViewDocSecurity($doc_key);
        if ($view_security) {
            $this->denyAccessUnlessGranted($view_security);
        }

        $this->denyUnsafePath($path);

        // Root Documentation Directory
        $doc_path = $this->getDocDir($doc_key);

        // Folder and file name of the page (ex : 20__Contenus/1__Articles => 20__Contenus / 1__Articles)
        $slashPosition = strrpos($path, '/');
        $dirPath = false === $slashPosition ? '' : substr($path, 0, $slashPosition);
        $filename = false === $slashPosition ? $path : substr($path, $slashPosition + 1);

        // Position and title, from the file name only (ex : 1__Articles => 1 / Articles)
        if (preg_match('/^(\d+)__(.+)$/', $filename, $matches)) {
            $position = (int) $matches[1];
            $title = $matches[2];
        } else {
            $position = 0;
            $title = $filename;
        }

        // Doc file Content
        $filePath = $doc_path . "/" . $path . '.md';
        if (!is_file($filePath)) {
            throw $this->createNotFoundException("The page \"$path\" does not exist.");
        }
        $docFileContent = $this->documentationService->getDocFileContent($filePath);

        $form = $this->createForm(MarkdownEditorType::class, [
            'position' => $position,
            'title' => $title,
            'content' => $docFileContent,
        ]);

        $form->handleRequest($request);

        if ($form->isSubmitted() && $form->isValid()) {

            $data = $form->getData();

            // New file name, in the same folder (ex : 20__Contenus/2__Articles)
            $newFileName = $data['position'] . '__' . trim($data['title']);
            $newPath = ('' !== $dirPath ? $dirPath . '/' : '') . $newFileName;
            $newFilePath = $doc_path . '/' . $newPath . '.md';

            // Renamed page : never replace another existing page
            if ($newPath !== $path && file_exists($newFilePath)) {
                $form->get('title')->addError(new FormError(
                    $translator->trans('A page with this name already exists.', [], 'ali_docs')
                ));
            } else {
                if ($newPath !== $path) {
                    rename($filePath, $newFilePath);
                }

                // Content
                file_put_contents($newFilePath, $this->sanitizeContent($data['content']));

                $this->addFlash('success', 'Content updated successfully!');

                return $this->redirectToRoute('ali_docs_admin_edit', [
                    'doc_key' => $doc_key,
                    'path' => $newPath,
                ]);
            }
        }

        $arg_render['doc_key'] = $doc_key;
        $arg_render['doc_title'] = $this->getDocTitle($doc_key);
        $arg_render['form'] = $form;
        $arg_render['content'] = $docFileContent;
        $arg_render['path'] = $path;
        $template = "@AliDocs/documentation/edit.html.twig";
        return $this->render($template, $arg_render);

    }


    public function docTree($doc_key, $current_url = ""): Response
    {
        // Sidebar : empty for a documentation the user can not read
        $security = $this->getViewDocSecurity($doc_key);
        if ($security && !$this->isGranted($security)) {
            return new Response('');
        }

        // Root Documentation Directory
        $doc_path = $this->getDocDir($doc_key);

        $arg_render['doc_key'] = $doc_key;
        $arg_render['switch_doc'] = $this->getSwitchDoc($doc_key);
        $arg_render['tree'] = $this->documentationService->getDirectoryTree($doc_path);
        $arg_render['current_url'] = $current_url;
        $template = "@AliDocs/documentation/_sidebar.html.twig";
        return $this->render($template, $arg_render);
    }


    /**
     * assetsFolder
     * File of the "assets" folder at the root of the documentation
     * The route looks like : #[Route('/{doc_key}/assets/{path}', name: 'ali_docs_asset')]
     */
    public function assetsFolder(string $doc_key, string $path): Response
    {
        return $this->asset($doc_key, 'assets/' . $path);
    }

    /**
     * asset
     * File of the documentation (image, video, pdf...), path relative to the documentation folder
     */
    public function asset(string $doc_key, string $path, $extension = null): Response
    {
        // Security first, then path check
        $security = $this->getViewDocSecurity($doc_key);
        if ($security) {
            $this->denyAccessUnlessGranted($security);
        }
        $this->denyUnsafePath($path);
        
        try {

            if($extension)
                $path = $path.$extension;

            // Security


            // Extensions autorisées
            // Allowed extensions and their fixed MIME type (never guessed from the file content)
            $mimeTypes = [
                'pdf' => 'application/pdf',
                'jpg' => 'image/jpeg',
                'jpeg' => 'image/jpeg',
                'png' => 'image/png',
                'mp4' => 'video/mp4',
                'webm' => 'video/webm',
            ];
            $extension = strtolower(pathinfo($path, PATHINFO_EXTENSION));
            if (!isset($mimeTypes[$extension])) {
                throw new \Exception("Extension not allowed: .$extension");
            }

            // Chemin absolu sécurisé
            $safePath = basename($path); // évite les `../` ou noms bizarres

            $filePath = $this->getDocDir($doc_key) . '/' . $path;

            // Vérification du fichier
            if (!file_exists($filePath) || !is_readable($filePath)) {
                throw new \Exception("File not found or not readable: $path");
            }



            // Type MIME
            $mimeType = $mimeTypes[$extension];

            // Streaming inline
            $response = new BinaryFileResponse($filePath);
            $response->headers->set('Content-Type', $mimeType);
            // The browser must not guess another type (ex : HTML in a .png file)
            $response->headers->set('X-Content-Type-Options', 'nosniff');



            $response->setContentDisposition(
                ResponseHeaderBag::DISPOSITION_INLINE,
                $safePath
            );

            return $response;

        } catch (\Throwable $e) {
            throw $this->createNotFoundException("The requested file does not exist or is not allowed.");
        }

    }



    /**
     * searchFiles
     * The route looks like : #[Route('/{doc_key}/search', name: 'ali_docs_search')]
     *
     * @param  mixed $request
     * @param  mixed $doc_key
     * @return Response
     */
    public function search(Request $request, $doc_key): Response
    {
        // Security
        $security = $this->getViewDocSecurity($doc_key);
        if ($security) {
            $this->denyAccessUnlessGranted($security);
        }

        // Root Documentation Directory
        $doc_path = $this->getDocDir($doc_key);

        // Search term
        $searchTerm = trim((string) $request->query->get('s', ''));

        // Pages matching by name first, then by content
        $nameResults = [];
        $contentResults = [];

        if ('' !== $searchTerm) {
            $finder = new Finder();
            $finder->in($doc_path)->files()->name('*.md')->sortByName(true);

            foreach ($finder as $file) {
                // Page url (ex : 20__Contenus/1__Articles)
                $pagePath = str_replace(DIRECTORY_SEPARATOR, '/', $file->getRelativePath());
                $pagePath = ltrim($pagePath . '/' . $file->getFilenameWithoutExtension(), '/');

                $result = [
                    'path' => $pagePath,
                    'name' => $this->documentationService->getPageName($pagePath),
                    'folders' => $this->documentationService->getBreadcrumbFolders($pagePath),
                ];

                // Readable text of the page (HTML tags and markdown syntax are ignored)
                $markdown = file_get_contents($file->getRealPath());
                $text = $this->documentationService->getPlainText($markdown);

                // Excerpt around the term found (or beginning of the page), headings excluded :
                // the first one usually repeats the page name already displayed
                $result['excerpt'] = $this->documentationService->getExcerpt(
                    $this->documentationService->getPlainText($markdown, false),
                    $searchTerm
                );

                // Search in the displayed names (folders and page, without the XX__ prefixes), then in the content
                $displayedName = implode(' ', [...array_column($result['folders'], 'name'), $result['name']]);
                if (false !== mb_stripos($displayedName, $searchTerm)) {
                    $nameResults[] = $result;
                } elseif (false !== mb_stripos($text, $searchTerm)) {
                    $contentResults[] = $result;
                }
            }
        }

        $arg_render['doc_key'] = $doc_key;
        $arg_render['doc_title'] = $this->getDocTitle($doc_key);
        $arg_render['searchTerm'] = $searchTerm;
        $arg_render['results'] = [...$nameResults, ...$contentResults];
        $template = "@AliDocs/documentation/search.html.twig";
        return $this->render($template, $arg_render);
    }


    /**
     * denyUnsafePath
     * Paths come from the url : refuse the ones going outside the documentation directory (../)
     */
    private function denyUnsafePath(string $path): void
    {
        $segments = explode('/', str_replace('\\', '/', $path));
        if (in_array('..', $segments, true) || str_contains($path, chr(0))) {
            throw $this->createNotFoundException('Invalid path.');
        }
    }

    public function getDocTitle($doc_key): string
    {
        $doc_key = $this->documentationService->normalizeDocKey($doc_key);
        return $this->getParameter('ali_docs.documentations')[$doc_key]['title'];
    }
    public function getDocDir($doc_key): string
    {
        $doc_key = $this->documentationService->normalizeDocKey($doc_key);
        return $this->getParameter('ali_docs.documentations')[$doc_key]['doc_dir'];
    }
    public function getViewDocSecurity($doc_key): ?string
    {
        $doc_key = $this->documentationService->normalizeDocKey($doc_key);
        $view_security = $this->getParameter('ali_docs.documentations')[$doc_key]['view_security'];
        if ($view_security && $view_security != "") {
            return $view_security;
        }
        return false;
    }

    /**
     * getEditDocSecurity
     * Role required to edit the documentation (always set : validated by the bundle configuration)
     */
    public function getEditDocSecurity($doc_key): string
    {
        $doc_key = $this->documentationService->normalizeDocKey($doc_key);

        return (string) ($this->getParameter('ali_docs.documentations')[$doc_key]['edit_security'] ?? '');
    }

    /**
     * getSwitchDoc
     * Documentations of the "Go to documentation" menu : only the ones the user can read
     * (switch_doc is resolved by the bundle configuration : "*" expanded, current documentation removed)
     *
     * @return array<array{doc_key: string, title: string}>
     */
    public function getSwitchDoc($doc_key): array
    {
        $doc_key = $this->documentationService->normalizeDocKey($doc_key);
        $switch_docs = $this->getParameter('ali_docs.documentations')[$doc_key]['switch_doc'] ?? [];

        $docs = [];
        foreach ($switch_docs as $switch_doc) {
            $security = $this->getViewDocSecurity($switch_doc);
            if ($security && !$this->isGranted($security)) {
                continue;
            }

            $docs[] = [
                // Key used in the urls ("_" => "-")
                'doc_key' => $this->documentationService->denormalizeDocKey($switch_doc),
                'title' => $this->getDocTitle($switch_doc),
            ];
        }

        return $docs;
    }

    public function sanitizeContent($content): string
    {
        return str_replace(
            [
                '\:',
                '\,',
                '\_',
                '\*',
                "\'",
                "\/",
            ],
            [
                ':',
                ',',
                '_',
                '*',
                "'",
                "/",
            ],
            $content
        );
    }

}
