<?php

namespace Aliarteo\AliDocsBundle\Controller;

use Aliarteo\AliDocsBundle\Entity\DocDir;
use Aliarteo\AliDocsBundle\Form\MarkdownEditorType;
use Aliarteo\AliDocsBundle\Markdown\MarkdownParser;
use Aliarteo\AliDocsBundle\Service\DocumentationService;
use Symfony\Bundle\FrameworkBundle\Controller\AbstractController;
use Symfony\Component\DependencyInjection\Attribute\Autowire;
use Symfony\Component\Finder\Finder;
use Symfony\Component\Form\FormError;
use Symfony\Component\HttpFoundation\File\UploadedFile;
use Symfony\Component\HttpFoundation\JsonResponse;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\String\Slugger\AsciiSlugger;
use Symfony\Contracts\Translation\TranslatorInterface;

/**
 * Edition of the documentations : edit page, preview, media files, new page / folder, deletion
 *
 * Every action requires the edit_security role AND the view_security role of the documentation,
 * the POST actions require the CSRF token "ali_docs_edit".
 * The routes are generated by the AliDocsRoutingLoader (one set of routes per documentation)
 */
class DocumentationAdminController extends AbstractController
{
    use DocumentationConfigTrait;

    private const CSRF_TOKEN_ID = 'ali_docs_edit';

    public function __construct(
        private DocumentationService $documentationService,
        private TranslatorInterface $translator,
        #[Autowire('%ali_docs.upload_max_size%')]
        private int $uploadMaxSize,
    ) {
    }

    /**
     * edit
     * The route looks like : #[Route('{admin_path}/{doc_key}/{path}', name: 'ali_docs_admin_edit', requirements: ['path' => '.+'])]
     */
    public function edit(Request $request, string $doc_key, string $path): Response
    {
        $this->denyAccessUnlessCanEdit($doc_key);
        $this->denyUnsafePath($path);

        // Root Documentation Directory
        $doc_path = $this->getDocDir($doc_key);

        // Folder and file name of the page (ex : 20__Contenus/1__Articles => 20__Contenus / 1__Articles)
        $dirPath = $this->getParentPath($path);
        $filename = '' === $dirPath ? $path : substr($path, strlen($dirPath) + 1);

        // Position and title, from the file name only (ex : 1__Articles => 1 / Articles)
        if (preg_match('/^(\d+)__(.+)$/', $filename, $matches)) {
            $position = (int) $matches[1];
            $title = $matches[2];
        } else {
            $position = 0;
            $title = $filename;
        }

        // Doc file Content
        $filePath = $doc_path . "/" . $path . '.md';
        if (!is_file($filePath)) {
            throw $this->createNotFoundException("The page \"$path\" does not exist.");
        }
        $docFileContent = $this->documentationService->getDocFileContent($filePath);

        $form = $this->createForm(MarkdownEditorType::class, [
            'position' => $position,
            'title' => $title,
            'content' => $docFileContent,
        ]);

        $form->handleRequest($request);

        if ($form->isSubmitted() && $form->isValid()) {

            $data = $form->getData();

            // New file name, in the same folder (ex : 20__Contenus/2__Articles)
            $newFileName = $data['position'] . '__' . trim($data['title']);
            $newPath = ('' !== $dirPath ? $dirPath . '/' : '') . $newFileName;
            $newFilePath = $doc_path . '/' . $newPath . '.md';

            // Renamed page : never replace another existing page
            if ($newPath !== $path && file_exists($newFilePath)) {
                $form->get('title')->addError(new FormError(
                    $this->translator->trans('A page with this name already exists.', [], 'ali_docs')
                ));
            } else {
                if ($newPath !== $path) {
                    rename($filePath, $newFilePath);
                }

                // Content : the browser sends the textarea lines with "\r\n", the line endings of the file are kept
                $content = str_replace("\r\n", "\n", (string) $data['content']);
                if (str_contains($docFileContent, "\r\n")) {
                    $content = str_replace("\n", "\r\n", $content);
                }
                file_put_contents($newFilePath, $content);

                $this->addFlash('success', 'Content updated successfully!');

                return $this->redirectToRoute('ali_docs_admin_edit', [
                    'doc_key' => $doc_key,
                    'path' => $newPath,
                ]);
            }
        }

        return $this->render('@AliDocs/documentation/edit.html.twig', [
            'doc_key' => $doc_key,
            'doc_title' => $this->getDocTitle($doc_key),
            'form' => $form,
            'path' => $path,
            'title' => $title,
            'breadcrumb' => $this->documentationService->getBreadcrumbFolders($path),
            'upload_max_size' => $this->formatSize($this->getUploadMaxSize()),
            'media_extensions' => array_keys(DocumentationService::MEDIA_TYPES),
        ]);
    }

    /**
     * create
     * New page or folder. The route looks like : #[Route('{admin_path}/_actions/{doc_key}/create', methods: ['POST'])]
     * Request : type (page | folder), parent (folder path, empty : root), position, title
     */
    public function create(Request $request, string $doc_key): Response
    {
        $this->denyAccessUnlessCanEdit($doc_key);
        $this->denyInvalidCsrfToken($request);

        $type = 'folder' === $request->request->get('type') ? 'folder' : 'page';
        $parent = trim((string) $request->request->get('parent', ''), '/');
        $parentDir = $this->getExistingDir($doc_key, $parent);

        $position = trim((string) $request->request->get('position', ''));
        $title = trim((string) $request->request->get('title', ''));

        $error = match (true) {
            !ctype_digit($position) => 'The position must be a positive number.',
            '' === $title => 'The name is required.',
            mb_strlen($title) > MarkdownEditorType::NAME_MAX_LENGTH,
            !preg_match(MarkdownEditorType::NAME_PATTERN, $title) => 'The page name can only contain letters, numbers, spaces, underscores or dashes.',
            default => null,
        };

        $name = (int) $position . '__' . $title;
        $newPath = ('' !== $parent ? $parent . '/' : '') . $name;

        // A page and a folder with the same name would have the same url
        if (null === $error && (file_exists($parentDir . '/' . $name) || file_exists($parentDir . '/' . $name . '.md'))) {
            $error = 'A page with this name already exists.';
        }

        if (null !== $error) {
            // Translated by the flash messages template (ali_docs domain)
            $this->addFlash('danger', $error);

            return $this->redirectToFolder($doc_key, $parent);
        }

        if ('folder' === $type) {
            mkdir($parentDir . '/' . $name);
            $this->addFlash('success', 'The folder has been created.');

            return $this->redirectToRoute('ali_docs_show', ['doc_key' => $doc_key, 'path' => $newPath]);
        }

        file_put_contents($parentDir . '/' . $name . '.md', '# ' . $title . "\n");
        $this->addFlash('success', 'The page has been created.');

        return $this->redirectToRoute('ali_docs_admin_edit', ['doc_key' => $doc_key, 'path' => $newPath]);
    }

    /**
     * delete
     * Page, or empty folder. The route looks like : #[Route('{admin_path}/_actions/{doc_key}/delete', methods: ['POST'])]
     * Request : path of the page / folder
     */
    public function delete(Request $request, string $doc_key): Response
    {
        $this->denyAccessUnlessCanEdit($doc_key);
        $this->denyInvalidCsrfToken($request);

        $path = trim((string) $request->request->get('path', ''), '/');
        $this->denyUnsafePath($path);
        if ('' === $path) {
            throw $this->createNotFoundException('The documentation root can not be deleted.');
        }

        $doc_path = $this->getDocDir($doc_key);
        $parent = $this->getParentPath($path);

        // Page : the media files are kept (they can be used by other pages)
        if (is_file($doc_path . '/' . $path . '.md')) {
            unlink($doc_path . '/' . $path . '.md');
            $this->addFlash('success', 'The page has been deleted.');

            return $this->redirectToFolder($doc_key, $parent);
        }

        $dir = $this->getExistingDir($doc_key, $path);
        if (!$this->documentationService->isFolderEmpty($dir)) {
            $this->addFlash('danger', 'Only an empty folder can be deleted.');

            return $this->redirectToFolder($doc_key, $path);
        }

        if (is_dir($dir . '/assets')) {
            rmdir($dir . '/assets');
        }
        rmdir($dir);
        $this->addFlash('success', 'The folder has been deleted.');

        return $this->redirectToFolder($doc_key, $parent);
    }

    /**
     * preview
     * HTML of the content being edited, as displayed on the page.
     * The route looks like : #[Route('{admin_path}/_actions/{doc_key}/preview', methods: ['POST'])]
     * Request : content, path of the page (relative images / videos)
     */
    public function preview(MarkdownParser $markdownParser, Request $request, string $doc_key): Response
    {
        $this->denyAccessUnlessCanEdit($doc_key);
        $this->denyInvalidCsrfToken($request);

        $path = trim((string) $request->request->get('path', ''), '/');
        $this->denyUnsafePath($path);

        $content = (string) $request->request->get('content', '');
        if (mb_strlen($content) > MarkdownEditorType::CONTENT_MAX_LENGTH) {
            return new Response('', Response::HTTP_REQUEST_ENTITY_TOO_LARGE);
        }

        // Same rendering as the page : cleaned HTML, absolute urls for the media files
        $html = $markdownParser->toHtml($content);
        $html = $markdownParser->replaceSrcUrls($html, $doc_key, $path);

        return new Response($html);
    }

    /**
     * mediaList
     * Media files of a folder of the documentation, its sub-folders and its breadcrumb (navigation between the folders).
     * The route looks like : #[Route('{admin_path}/_actions/{doc_key}/media', methods: ['GET'])]
     * Query : path of the page, folder browsed (default : folder of the page)
     */
    public function mediaList(Request $request, string $doc_key): JsonResponse
    {
        $this->denyAccessUnlessCanEdit($doc_key);

        $pageFolder = $this->getPageFolder((string) $request->query->get('path', ''));
        $folder = $this->getBrowsedFolder($request->query->has('folder') ? (string) $request->query->get('folder') : $pageFolder);
        $dir = $this->getExistingDir($doc_key, $folder);

        // Sub-folders (the "assets" folders are not documentation folders), in the order of the menu
        $folders = [];
        foreach (scandir($dir) as $name) {
            if ('.' !== $name[0] && 'assets' !== $name && is_dir($dir . '/' . $name)) {
                $folders[] = $name;
            }
        }
        usort($folders, 'strnatcmp');
        $folders = array_map(fn (string $name): array => [
            'name' => $this->documentationService->getPageName($name),
            'path' => ('' !== $folder ? $folder . '/' : '') . $name,
        ], $folders);

        // Media files of the "assets" folder, and the ones stored directly in the folder (ex : videos next to the pages)
        $files = [];
        foreach (['assets/', ''] as $subFolder) {
            $mediaDir = $dir . '/' . $subFolder;
            if (!is_dir($mediaDir)) {
                continue;
            }
            foreach (scandir($mediaDir) as $name) {
                if (is_file($mediaDir . $name) && isset(DocumentationService::MEDIA_TYPES[strtolower(pathinfo($name, PATHINFO_EXTENSION))])) {
                    $files[] = $this->getMediaInfo($doc_key, $pageFolder, $folder, $subFolder . $name);
                }
            }
        }

        // Breadcrumb : documentation root > folders > browsed folder
        $breadcrumb = $this->documentationService->getBreadcrumbFolders($folder);
        if ('' !== $folder) {
            $breadcrumb[] = ['name' => $this->documentationService->getPageName($folder), 'path' => $folder];
        }

        return $this->json([
            'folder' => $folder,
            'page_folder' => $pageFolder,
            'breadcrumb' => $breadcrumb,
            'folders' => $folders,
            'files' => $files,
        ]);
    }

    /**
     * pages
     * Pages and folders of the documentation, with their link relative to the page being edited (link modal).
     * The route looks like : #[Route('{admin_path}/_actions/{doc_key}/pages', methods: ['GET'])]
     * Query : path of the page
     */
    public function pages(Request $request, string $doc_key): JsonResponse
    {
        $this->denyAccessUnlessCanEdit($doc_key);

        $pageFolder = $this->getPageFolder((string) $request->query->get('path', ''));
        $tree = $this->documentationService->getDirectoryTree($this->getDocDir($doc_key));

        $items = [];
        $walk = function (DocDir $dir, int $depth) use (&$walk, &$items, $pageFolder): void {
            foreach ($dir->getChildren() as $child) {
                $url = $child->getUrl();
                $relative = $this->getRelativePath($pageFolder, $this->getParentPath($url));
                $link = ('' !== $relative ? $relative . '/' : '') . basename($url) . ($child->isDirectory() ? '' : '.md');

                $items[] = [
                    'type' => $child->isDirectory() ? 'folder' : 'page',
                    'name' => $child->getName(),
                    'depth' => $depth,
                    // Markdown links stop at the first space : spaces written %20
                    'link' => str_replace(' ', '%20', $link),
                ];

                if ($child instanceof DocDir) {
                    $walk($child, $depth + 1);
                }
            }
        };
        $walk($tree, 0);

        return $this->json(['items' => $items]);
    }

    /**
     * mediaUpload
     * Upload of media files in the "assets" folder next to the page.
     * The route looks like : #[Route('{admin_path}/_actions/{doc_key}/media', methods: ['POST'])]
     * Request : path of the page, files[]
     */
    public function mediaUpload(Request $request, string $doc_key): JsonResponse
    {
        $this->denyAccessUnlessCanEdit($doc_key);

        // Request larger than post_max_size : PHP drops the whole request (no token, no file)
        if (0 === $request->request->count() && 0 === $request->files->count() && (int) $request->server->get('CONTENT_LENGTH') > 0) {
            return $this->json([
                'files' => [],
                'errors' => [$this->trans('The file is too large (max %size%).', ['%size%' => $this->formatSize($this->getUploadMaxSize())])],
            ], Response::HTTP_REQUEST_ENTITY_TOO_LARGE);
        }

        $this->denyInvalidCsrfToken($request);

        $pageFolder = $this->getPageFolder((string) $request->request->get('path', ''));
        // Destination : "assets" folder of the browsed folder (default : folder of the page)
        $folder = $this->getBrowsedFolder($request->request->has('folder') ? (string) $request->request->get('folder') : $pageFolder);
        $assetsDir = $this->getExistingDir($doc_key, $folder) . '/assets';

        $uploadedFiles = $request->files->all('files');
        $slugger = new AsciiSlugger();
        $files = [];
        $errors = [];

        foreach ($uploadedFiles as $file) {
            if (!$file instanceof UploadedFile) {
                continue;
            }

            $error = $this->getUploadError($file);
            if (null !== $error) {
                $errors[] = $file->getClientOriginalName() . ' : ' . $error;
                continue;
            }

            // File name : ascii slug (no space, no accent : simple Markdown links), never replace an existing file
            $extension = strtolower($file->getClientOriginalExtension());
            $baseName = $slugger->slug(pathinfo($file->getClientOriginalName(), PATHINFO_FILENAME))->lower()->toString() ?: 'file';
            $name = $baseName . '.' . $extension;
            for ($i = 2; file_exists($assetsDir . '/' . $name); ++$i) {
                $name = $baseName . '-' . $i . '.' . $extension;
            }

            $file->move($assetsDir, $name);
            $files[] = $this->getMediaInfo($doc_key, $pageFolder, $folder, 'assets/' . $name);
        }

        if ([] === $uploadedFiles) {
            $errors[] = $this->trans('No file received.');
        }

        return $this->json(['files' => $files, 'errors' => $errors]);
    }

    /**
     * mediaDelete
     * Deletion of a media file of a folder ("assets" folder, or stored directly in the folder).
     * The route looks like : #[Route('{admin_path}/_actions/{doc_key}/media/delete', methods: ['POST'])]
     * Request : folder, file (ex : "assets/export.png"), force (deleted even if used in pages)
     */
    public function mediaDelete(Request $request, string $doc_key): JsonResponse
    {
        $this->denyAccessUnlessCanEdit($doc_key);
        $this->denyInvalidCsrfToken($request);

        $folder = $this->getBrowsedFolder((string) $request->request->get('folder', ''));
        $dir = $this->getExistingDir($doc_key, $folder);

        // Only a media file of the folder or of its "assets" folder
        $file = (string) $request->request->get('file', '');
        $name = str_starts_with($file, 'assets/') ? substr($file, \strlen('assets/')) : $file;
        // A file name only : no folder separator, no NUL character, no hidden file (., ..)
        if ('' === $name || false !== strpbrk($name, "/\\\0") || '.' === $name[0]
            || !isset(DocumentationService::MEDIA_TYPES[strtolower(pathinfo($name, PATHINFO_EXTENSION))])
            || !is_file($dir . '/' . $file)) {
            throw $this->createNotFoundException('This file does not exist.');
        }

        // Used in pages : confirmation required (force)
        if (!$request->request->getBoolean('force')) {
            $usedIn = $this->findMediaUsage($doc_key, $name);
            if ([] !== $usedIn) {
                return $this->json(['used_in' => $usedIn]);
            }
        }

        unlink($dir . '/' . $file);

        return $this->json(['deleted' => $name]);
    }

    /**
     * Pages of the documentation containing the file name (written as is or with %20) : approximate,
     * a file with the same name in another folder is also found
     *
     * @return string[] Names of the pages
     */
    private function findMediaUsage(string $doc_key, string $name): array
    {
        $docDir = $this->getDocDir($doc_key);
        $searched = array_unique([$name, str_replace(' ', '%20', $name), rawurlencode($name)]);

        $pages = [];
        foreach ((new Finder())->files()->in($docDir)->name('*.md')->sortByName(true) as $page) {
            $content = $page->getContents();
            foreach ($searched as $text) {
                if (str_contains($content, $text)) {
                    $pages[] = $this->documentationService->getPageName(substr(str_replace('\\', '/', $page->getRelativePathname()), 0, -3));
                    break;
                }
            }
        }

        return $pages;
    }

    /**
     * Error of an uploaded file (null : valid) : PHP upload error, size, extension, real content type
     */
    private function getUploadError(UploadedFile $file): ?string
    {
        if (!$file->isValid()) {
            return \UPLOAD_ERR_INI_SIZE === $file->getError() || \UPLOAD_ERR_FORM_SIZE === $file->getError()
                ? $this->trans('The file is too large (max %size%).', ['%size%' => $this->formatSize($this->getUploadMaxSize())])
                : $file->getErrorMessage();
        }

        if ($file->getSize() > $this->getUploadMaxSize()) {
            return $this->trans('The file is too large (max %size%).', ['%size%' => $this->formatSize($this->getUploadMaxSize())]);
        }

        $extension = strtolower($file->getClientOriginalExtension());
        $allowed = DocumentationService::MEDIA_TYPES;
        if (!isset($allowed[$extension])) {
            return $this->trans('File type not allowed. Allowed types : %types%.', ['%types%' => implode(', ', array_keys($allowed))]);
        }

        // The content must match the extension (ex : no HTML or SVG in a .png file)
        $mimeType = (string) $file->getMimeType();
        $expected = $allowed[$extension];
        $compatible = $mimeType === $expected
            || ('mp4' === $extension && 'application/mp4' === $mimeType)
            || ('webm' === $extension && 'audio/webm' === $mimeType);
        if (!$compatible) {
            return $this->trans('The content of the file does not match its extension.');
        }

        return null;
    }

    /**
     * Media file of a folder : name, type, url and Markdown code to insert in the page
     * (path relative to the folder of the page, ex : ../50__Exports/assets/export.png)
     *
     * @param string $file File in the folder (ex : "assets/export.png", or "video.mp4" stored next to the pages)
     *
     * @return array{name: string, kind: string, url: string, markdown: string, block: bool}
     */
    private function getMediaInfo(string $doc_key, string $pageFolder, string $folder, string $file): array
    {
        $name = basename($file);
        $kind = DocumentationService::getMediaKind($name);
        $label = pathinfo($name, PATHINFO_FILENAME);
        $relative = $this->getRelativePath($pageFolder, $folder);
        $src = ('' !== $relative ? $relative . '/' : '') . $file;
        // Markdown links stop at the first space : spaces written %20 (HTML attributes : as is)
        $markdownSrc = str_replace(' ', '%20', $src);

        $markdown = match ($kind) {
            'image' => '![' . $label . '](' . $markdownSrc . ')',
            'video' => "<video width=\"100%\" controls>\n  <source src=\"" . htmlspecialchars($src, \ENT_QUOTES) . '" type="' . DocumentationService::MEDIA_TYPES[strtolower(pathinfo($name, PATHINFO_EXTENSION))] . "\">\n</video>",
            default => '[' . $label . '](' . $markdownSrc . ')',
        };

        return [
            'name' => $name,
            'kind' => $kind,
            'url' => $this->generateUrl('ali_docs_show', [
                'doc_key' => $doc_key,
                'path' => ('' !== $folder ? $folder . '/' : '') . $file,
            ]),
            'markdown' => $markdown,
            // File in the folder (deletion)
            'file' => $file,
            // Video : HTML block, on its own lines
            'block' => 'video' === $kind,
        ];
    }

    /**
     * Relative path from a folder to another one (ex : 30__Users => 50__Exports/10__Csv : ../50__Exports/10__Csv)
     */
    private function getRelativePath(string $from, string $to): string
    {
        $from = '' === $from ? [] : explode('/', $from);
        $to = '' === $to ? [] : explode('/', $to);

        while ([] !== $from && [] !== $to && $from[0] === $to[0]) {
            array_shift($from);
            array_shift($to);
        }

        return implode('/', [...array_fill(0, \count($from), '..'), ...$to]);
    }

    /**
     * Folder of the page being edited (path checked)
     */
    private function getPageFolder(string $pagePath): string
    {
        $pagePath = trim($pagePath, '/');
        $this->denyUnsafePath($pagePath);

        return $this->getParentPath($pagePath);
    }

    /**
     * Folder browsed in the media modal : a documentation folder, never an "assets" folder
     */
    private function getBrowsedFolder(string $folder): string
    {
        $folder = trim($folder, '/');
        $this->denyUnsafePath($folder);
        if (in_array('assets', explode('/', $folder), true)) {
            throw $this->createNotFoundException('Invalid folder.');
        }

        return $folder;
    }

    /**
     * Edit role AND view role of the documentation (the edit pages show the content)
     */
    private function denyAccessUnlessCanEdit(string $doc_key): void
    {
        // The edition always requires a role : it writes files on the server
        $edit_security = $this->getEditDocSecurity($doc_key);
        if ('' === $edit_security) {
            throw $this->createAccessDeniedException('No edit_security configured for this documentation.');
        }
        $this->denyAccessUnlessGranted($edit_security);

        $view_security = $this->getViewDocSecurity($doc_key);
        if ($view_security) {
            $this->denyAccessUnlessGranted($view_security);
        }
    }

    private function denyInvalidCsrfToken(Request $request): void
    {
        if (!$this->isCsrfTokenValid(self::CSRF_TOKEN_ID, (string) $request->request->get('_token'))) {
            throw $this->createAccessDeniedException('Invalid CSRF token.');
        }
    }

    /**
     * Absolute path of an existing folder of the documentation (404 otherwise : no access outside the documentation)
     */
    private function getExistingDir(string $doc_key, string $path): string
    {
        $this->denyUnsafePath($path);

        $root = realpath($this->getDocDir($doc_key));
        $dir = realpath($root . ('' !== $path ? '/' . $path : ''));

        if (false === $root || false === $dir || !is_dir($dir) || ($dir !== $root && !str_starts_with($dir, $root . \DIRECTORY_SEPARATOR))) {
            throw $this->createNotFoundException('This folder does not exist.');
        }

        return $dir;
    }

    /**
     * Folder of a page / folder path (ex : 20__Contenus/1__Articles => 20__Contenus, 1__Articles => "")
     */
    private function getParentPath(string $path): string
    {
        $position = strrpos($path, '/');

        return false === $position ? '' : substr($path, 0, $position);
    }

    private function redirectToFolder(string $doc_key, string $folder): Response
    {
        return '' === $folder
            ? $this->redirectToRoute('ali_docs_index', ['doc_key' => $doc_key])
            : $this->redirectToRoute('ali_docs_show', ['doc_key' => $doc_key, 'path' => $folder]);
    }

    /**
     * Maximum size of an uploaded file : the configuration, limited by the PHP configuration
     */
    private function getUploadMaxSize(): int
    {
        return (int) min($this->uploadMaxSize, UploadedFile::getMaxFilesize());
    }

    private function formatSize(int $bytes): string
    {
        return $bytes >= 1024 ** 2
            ? round($bytes / 1024 ** 2) . ' ' . $this->trans('MB')
            : round($bytes / 1024) . ' ' . $this->trans('KB');
    }

    private function trans(string $message, array $parameters = []): string
    {
        return $this->translator->trans($message, $parameters, 'ali_docs');
    }
